CREATE TABLE users (
    user_id               BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    email                 VARCHAR(255),
    password_hash         VARCHAR(255),
    name                  VARCHAR(50),
    nickname              VARCHAR(30),
    birth_date            DATE,
    notification_enabled  BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ,
    deleted_at            TIMESTAMPTZ,

    CONSTRAINT pk_users                        PRIMARY KEY (user_id),
    CONSTRAINT uk_users_email                  UNIQUE (email),
    CONSTRAINT uk_users_nickname               UNIQUE (nickname),
    CONSTRAINT ck_users_withdrawn_anonymized   CHECK (
        deleted_at IS NULL
        OR (
            email IS NULL
            AND password_hash IS NULL
            AND name IS NULL
            AND nickname IS NULL
            AND birth_date IS NULL
        )
    )
);

COMMENT ON TABLE  users                       IS '회원. 탈퇴 시 행은 남기고 개인정보를 NULL로 덮어 익명화 (남긴 평가는 익명 집계에 유지)';
COMMENT ON COLUMN users.user_id               IS '회원 ID';
COMMENT ON COLUMN users.email                 IS '로그인 이메일 UNIQUE. 서버가 소문자로 정규화해 저장. 탈퇴 시 NULL';
COMMENT ON COLUMN users.password_hash         IS '비밀번호 해시. 구글 전용 계정·탈퇴 시 NULL';
COMMENT ON COLUMN users.name                  IS '이름. 탈퇴 시 NULL';
COMMENT ON COLUMN users.nickname              IS '닉네임 UNIQUE. 탈퇴 시 NULL';
COMMENT ON COLUMN users.birth_date            IS '만 14세 확인용 (검사는 서버). 구글 가입은 가입 마무리 때 입력. 탈퇴 시 NULL';
COMMENT ON COLUMN users.notification_enabled  IS '설정: 알림(푸시) 켜기/끄기. 꺼도 알림함에는 쌓임';
COMMENT ON COLUMN users.created_at            IS '가입 시각';
COMMENT ON COLUMN users.updated_at            IS '정보 수정 시각 (애플리케이션이 기록)';
COMMENT ON COLUMN users.deleted_at            IS '탈퇴 시각. NULL이면 활동 중인 회원';


CREATE TABLE user_social_accounts (
    social_account_id  BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    user_id            BIGINT        NOT NULL,
    provider           VARCHAR(20)   NOT NULL,
    provider_user_id   VARCHAR(255)  NOT NULL,
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT pk_user_social_accounts           PRIMARY KEY (social_account_id),
