CREATE TABLE groups (
    group_id     BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    name         VARCHAR(50)   NOT NULL,
    invite_code  VARCHAR(20)   NOT NULL,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    deleted_at   TIMESTAMPTZ,

    CONSTRAINT pk_groups              PRIMARY KEY (group_id),
    CONSTRAINT uk_groups_invite_code  UNIQUE (invite_code),
    CONSTRAINT ck_groups_name         CHECK (btrim(name) <> '')
);

COMMENT ON TABLE  groups             IS '그룹. 마지막 멤버가 나가면 닫힘(deleted_at)';
COMMENT ON COLUMN groups.group_id    IS '그룹 ID';
COMMENT ON COLUMN groups.name        IS '그룹 이름 (공백만 있는 이름 불가)';
COMMENT ON COLUMN groups.invite_code IS '초대 코드 UNIQUE. 재발급 시 교체, 이전 코드 즉시 무효';
COMMENT ON COLUMN groups.created_at  IS '만든 시각';
COMMENT ON COLUMN groups.deleted_at  IS '마지막 멤버가 나가 닫힌 시각. NULL이면 활성';


CREATE TABLE group_members (
    group_id   BIGINT        NOT NULL,
    user_id    BIGINT        NOT NULL,
    role       VARCHAR(10)   NOT NULL DEFAULT 'MEMBER',
    status     VARCHAR(10)   NOT NULL DEFAULT 'ACTIVE',
    joined_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    left_at    TIMESTAMPTZ,

    CONSTRAINT pk_group_members          PRIMARY KEY (group_id, user_id),
    CONSTRAINT fk_group_members_group    FOREIGN KEY (group_id) REFERENCES groups (group_id),
    CONSTRAINT fk_group_members_user     FOREIGN KEY (user_id)  REFERENCES users (user_id),
    CONSTRAINT ck_group_members_role     CHECK (role IN ('OWNER', 'MEMBER')),
    CONSTRAINT ck_group_members_status   CHECK (status IN ('ACTIVE', 'LEFT', 'KICKED')),
    CONSTRAINT ck_group_members_left_at  CHECK (
        (status = 'ACTIVE' AND left_at IS NULL)
        OR (status <> 'ACTIVE' AND left_at IS NOT NULL)
    )
);

-- 내 그룹 목록 (PK가 group_id부터라 user_id 조회에는 별도 인덱스가 필요)
CREATE INDEX ix_group_members_user_status ON group_members (user_id, status);

-- ACTIVE 그룹장은 그룹당 1명. 위임할 때는 기존 OWNER를 MEMBER로 먼저 바꾼 뒤 새 OWNER 지정
CREATE UNIQUE INDEX uk_group_members_active_owner
    ON group_members (group_id)
    WHERE role = 'OWNER' AND status = 'ACTIVE';

COMMENT ON TABLE  group_members           IS '그룹 멤버십. 나가거나 강퇴돼도 행 유지 (재참여 차단·재참여 시 같은 행 갱신)';
COMMENT ON COLUMN group_members.group_id  IS '그룹';
COMMENT ON COLUMN group_members.user_id   IS '회원';
COMMENT ON COLUMN group_members.role      IS 'OWNER / MEMBER. ACTIVE 그룹장은 그룹당 1명 (위임: 기존 OWNER를 MEMBER로 먼저 변경)';
COMMENT ON COLUMN group_members.status    IS 'ACTIVE / LEFT 나감 / KICKED 강퇴 (재참여 차단용으로 행 유지)';
COMMENT ON COLUMN group_members.joined_at IS '참여 시각 (재참여 시 갱신). 업로드 이후 들어온 사람은 그 코디를 평가하지 않음';
COMMENT ON COLUMN group_members.left_at   IS '나가거나 강퇴된 시각. ACTIVE면 NULL (재참여 시 NULL로)';


