    CONSTRAINT ck_user_social_accounts_provider  CHECK (provider IN ('GOOGLE'))
);

CREATE INDEX ix_user_social_accounts_user ON user_social_accounts (user_id);

COMMENT ON TABLE  user_social_accounts                   IS '소셜 로그인 연결. 탈퇴 시 서버가 삭제';
COMMENT ON COLUMN user_social_accounts.social_account_id IS '연결 ID';
COMMENT ON COLUMN user_social_accounts.user_id           IS '회원';
COMMENT ON COLUMN user_social_accounts.provider          IS 'GOOGLE. UNIQUE: provider + provider_user_id';
COMMENT ON COLUMN user_social_accounts.provider_user_id  IS '제공자가 준 고유 ID (sub)';
COMMENT ON COLUMN user_social_accounts.created_at        IS '연결 시각';


CREATE TABLE signup_tokens (
    token_hash        CHAR(64)      NOT NULL,
    provider          VARCHAR(20)   NOT NULL,
    provider_user_id  VARCHAR(255)  NOT NULL,
    email             VARCHAR(255),
    name              VARCHAR(50),
    expires_at        TIMESTAMPTZ   NOT NULL,
    used_at           TIMESTAMPTZ,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT pk_signup_tokens           PRIMARY KEY (token_hash),
    CONSTRAINT ck_signup_tokens_provider  CHECK (provider IN ('GOOGLE'))
);

CREATE INDEX ix_signup_tokens_expires ON signup_tokens (expires_at);

COMMENT ON TABLE  signup_tokens                  IS '구글 첫 로그인 → 가입 마무리 사이에만 쓰는 1회용 토큰. 회원이 아직 없어 FK 없음';
COMMENT ON COLUMN signup_tokens.token_hash       IS 'signupToken의 SHA-256 해시 (16진수 64자). 원문은 저장하지 않음';
COMMENT ON COLUMN signup_tokens.provider         IS 'GOOGLE';
COMMENT ON COLUMN signup_tokens.provider_user_id IS '제공자 고유 ID (sub)';
COMMENT ON COLUMN signup_tokens.email            IS '구글이 준 이메일';
COMMENT ON COLUMN signup_tokens.name             IS '구글이 준 이름 (가입 화면 기본값)';
COMMENT ON COLUMN signup_tokens.expires_at       IS '만료 시각 (발급 + 10분)';
COMMENT ON COLUMN signup_tokens.used_at          IS '사용 시각 (1회용: used_at IS NULL 조건부 갱신)';
COMMENT ON COLUMN signup_tokens.created_at       IS '발급 시각';


CREATE TABLE refresh_tokens (
    token_id    BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT        NOT NULL,
    token_hash  CHAR(64)      NOT NULL,
    expires_at  TIMESTAMPTZ   NOT NULL,
    revoked_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT pk_refresh_tokens          PRIMARY KEY (token_id),
    CONSTRAINT uk_refresh_tokens_hash     UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user     FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE INDEX ix_refresh_tokens_user    ON refresh_tokens (user_id);
CREATE INDEX ix_refresh_tokens_expires ON refresh_tokens (expires_at);

COMMENT ON TABLE  refresh_tokens            IS 'refreshToken (14일, 재발급마다 교체). 탈퇴 시 서버가 삭제';
COMMENT ON COLUMN refresh_tokens.token_id   IS '토큰 ID';
COMMENT ON COLUMN refresh_tokens.user_id    IS '회원';
COMMENT ON COLUMN refresh_tokens.token_hash IS 'refreshToken의 SHA-256 해시 UNIQUE. 원문은 저장하지 않음';
COMMENT ON COLUMN refresh_tokens.expires_at IS '만료 시각 (발급 + 14일)';
COMMENT ON COLUMN refresh_tokens.revoked_at IS '폐기 시각 (재발급 rotation·로그아웃·탈퇴)';
COMMENT ON COLUMN refresh_tokens.created_at IS '발급 시각';


