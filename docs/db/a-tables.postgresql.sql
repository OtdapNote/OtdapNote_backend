    subscription_id  BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    user_id          BIGINT        NOT NULL,
    endpoint         VARCHAR(500)  NOT NULL,
    p256dh           VARCHAR(255)  NOT NULL,
    auth             VARCHAR(255)  NOT NULL,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT pk_push_subscriptions           PRIMARY KEY (subscription_id),
    CONSTRAINT uk_push_subscriptions_endpoint  UNIQUE (endpoint),
    CONSTRAINT fk_push_subscriptions_user      FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE INDEX ix_push_subscriptions_user ON push_subscriptions (user_id);

COMMENT ON TABLE  push_subscriptions                 IS '웹 푸시 구독. 기기 1대 = 1행. 탈퇴 시 서버가 삭제, 푸시 서버가 404·410이면 삭제';
COMMENT ON COLUMN push_subscriptions.subscription_id IS '구독 ID';
COMMENT ON COLUMN push_subscriptions.user_id         IS '회원';
COMMENT ON COLUMN push_subscriptions.endpoint        IS '브라우저가 준 푸시 주소 UNIQUE. 같은 endpoint면 갱신';
COMMENT ON COLUMN push_subscriptions.p256dh          IS '웹 푸시 암호화 키';
COMMENT ON COLUMN push_subscriptions.auth            IS '웹 푸시 인증 비밀값';
COMMENT ON COLUMN push_subscriptions.created_at      IS '등록 시각';


CREATE TABLE notifications (
    notification_id  BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    user_id          BIGINT        NOT NULL,
    type             VARCHAR(30)   NOT NULL,
    group_id         BIGINT,
    outfit_id        BIGINT,       -- FK(→ outfits, ON DELETE CASCADE)는 outfits 생성 후 추가
    read_at          TIMESTAMPTZ,
    pushed_at        TIMESTAMPTZ,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT pk_notifications        PRIMARY KEY (notification_id),
    CONSTRAINT fk_notifications_user   FOREIGN KEY (user_id)  REFERENCES users (user_id),
    CONSTRAINT fk_notifications_group  FOREIGN KEY (group_id) REFERENCES groups (group_id) ON DELETE SET NULL,
    CONSTRAINT ck_notifications_type   CHECK (type IN ('NEW_OUTFIT', 'RATING_RECEIVED', 'RESULT_OPENED', 'VOTE_CLOSED'))
);

-- 알림함: 최신순 + 커서(이 ID보다 작은 것)
CREATE INDEX ix_notifications_user_id_desc ON notifications (user_id, notification_id DESC);

-- 상단 배지: 안 읽은 알림만 담는 부분 인덱스
CREATE INDEX ix_notifications_user_unread ON notifications (user_id) WHERE read_at IS NULL;

-- 코디 삭제 시 CASCADE 대상 찾기 (FK 컬럼은 자동으로 인덱스가 생기지 않음)
CREATE INDEX ix_notifications_outfit ON notifications (outfit_id);

COMMENT ON TABLE  notifications                 IS '앱 안 알림함. 알림 설정과 무관하게 쌓임. 탈퇴 시 서버가 삭제';
COMMENT ON COLUMN notifications.notification_id IS '알림 ID';
COMMENT ON COLUMN notifications.user_id         IS '받는 사람';
COMMENT ON COLUMN notifications.type            IS 'NEW_OUTFIT / RESULT_OPENED / VOTE_CLOSED / RATING_RECEIVED(MVP 미사용, 확장용)';
COMMENT ON COLUMN notifications.group_id        IS '관련 그룹 (그룹 행 삭제 시 NULL)';
COMMENT ON COLUMN notifications.outfit_id       IS '관련 코디 (코디 삭제 시 함께 삭제)';
COMMENT ON COLUMN notifications.read_at         IS '읽은 시각 (NULL이면 안 읽음 → 상단 배지)';
COMMENT ON COLUMN notifications.pushed_at       IS '푸시로 보낸 시각 (MVP는 RESULT_OPENED만, 알림 설정이 켜져 있을 때만)';
COMMENT ON COLUMN notifications.created_at      IS '만든 시각';